-- Run this once in the SQL editor of the Supabase project that holds mycarco_db.
-- Safe / non-destructive: it only adds columns and a categories table.

ALTER TABLE mycarco_db.mc_blog ADD COLUMN IF NOT EXISTS meta_title text;
ALTER TABLE mycarco_db.mc_blog ADD COLUMN IF NOT EXISTS meta_description text;
ALTER TABLE mycarco_db.mc_blog ADD COLUMN IF NOT EXISTS primary_cta jsonb
  DEFAULT '{"enabled": false, "headline": "", "button_text": "", "url": ""}'::jsonb;
ALTER TABLE mycarco_db.mc_blog ADD COLUMN IF NOT EXISTS heading_styles jsonb;

CREATE TABLE IF NOT EXISTS mycarco_db.mc_blog_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  slug text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Seed categories from posts that already have one.
INSERT INTO mycarco_db.mc_blog_categories (name, slug)
SELECT DISTINCT category,
       regexp_replace(regexp_replace(lower(category), '[^a-z0-9]+', '-', 'g'), '(^-|-$)', '', 'g')
FROM mycarco_db.mc_blog
WHERE category IS NOT NULL AND btrim(category) <> ''
ON CONFLICT DO NOTHING;
